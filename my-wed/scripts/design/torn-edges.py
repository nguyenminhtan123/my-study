"""Torn-paper edges for template 13, as SVG masks (data URIs) printed as SCSS variables.

Each torn photo has two edges per side: the outer edge of the paper, and an inner edge where the printed
photo stops, a few pixels in, so a thin white fibrous rim shows like a real torn print.
Run: python3 scripts/design/torn-edges.py > src/templates/t13/_torn.scss
"""

import math
import random
import sys
from urllib.parse import quote

W, H = 1000, 30  # viewBox: the mask is drawn at 100% x 30px, so one unit is one pixel vertically
STEP = 4


def noise(rng, n, octaves):
    """Sum of random-phase sines: smooth tearing with finer rough bits on top."""
    waves = [(rng.uniform(0, 2 * math.pi), f, a) for f, a in octaves]
    out = []
    for i in range(n):
        x = i / (n - 1)
        out.append(sum(a * math.sin(2 * math.pi * f * x + p) for p, f, a in waves))
    return out


def edge(seed, mode):
    rng = random.Random(seed)
    n = W // STEP + 1
    xs = [i / (n - 1) for i in range(n)]
    clamp = lambda v: max(0.5, min(H - 0.5, v))
    if mode == "wave":
        # a soft sea wave, with a white band of foam the same width all along
        f, p = rng.uniform(2.2, 2.8), rng.uniform(0, 2 * math.pi)
        outer = [13 + 8 * math.sin(2 * math.pi * f * x + p) + 1.5 * math.sin(2 * math.pi * 2 * f * x + p) for x in xs]
        inner = [o + 5 for o in outer]
    elif mode == "shell":
        # a scalloped edge, like the rim of a seashell or a lace trim: round bumps about 24px wide
        period = 62
        outer, inner = [], []
        for i in range(n):
            t = ((i * STEP) % period) / period * 2 - 1  # -1..1 across one bump
            bump = 8 * math.sqrt(max(0.0, 1 - t * t))
            outer.append(18 - bump)
            inner.append(18 - bump + 5)
    else:  # foam: a soft wave whose white rim bubbles like foam on the sand
        f, p = rng.uniform(2.0, 2.6), rng.uniform(0, 2 * math.pi)
        outer = [12 + 7 * math.sin(2 * math.pi * f * x + p) for x in xs]
        bubbles = noise(rng, n, [(rng.uniform(28, 34), 1.6), (rng.uniform(55, 65), 1.0)])
        inner = [o + 6 + abs(b) * 1.6 for o, b in zip(outer, bubbles)]
    return [clamp(v) for v in outer], [clamp(v) for v in inner]


def svg(ys, bottom):
    pts = []
    for i, y in enumerate(ys):
        x = min(W, i * STEP)
        pts.append(f"{x} {round(H - y if bottom else y, 1)}")
    base = 0 if bottom else H
    d = f"M0 {base}L" + "L".join(pts) + f"L{W} {base}Z"
    s = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {W} {H}' preserveAspectRatio='none'><path d='{d}'/></svg>"
    return 'url("data:image/svg+xml,' + quote(s, safe=" '=:/,.") + '")'


MODE = sys.argv[1] if len(sys.argv) > 1 else "wave"
print("// generated by scripts/design/torn-edges.py: torn-paper edge masks (outer paper edge, inner photo edge)")
for name, seed in [("a-top", 11), ("a-bottom", 23), ("b-top", 37), ("b-bottom", 41), ("c-top", 53), ("c-bottom", 67)]:
    outer, inner = edge(seed, MODE)
    bottom = name.endswith("bottom")
    print(f"$torn-{name}-paper: {svg(outer, bottom)};")
    print(f"$torn-{name}-photo: {svg(inner, bottom)};")
